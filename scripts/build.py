#!/usr/bin/env python3
"""Build Jace Browser from Firefox's source.

    python3 scripts/build.py download              # Firefox source -> engine/
    python3 scripts/build.py prepare [--usb-helper PATH]
                                                   # add Jace Browser to engine/
    python3 scripts/build.py vs-sdk                # (Windows cross-build) Visual Studio SDK
    python3 scripts/build.py build                 # ./mach build (hours, the first time)
    python3 scripts/build.py package               # installers -> dist/
    python3 scripts/build.py all                   # all of the above

Options: --platform linux|windows|macos (default: this computer; "windows"
means cross-compiling from Linux, the way Mozilla builds Firefox).

What "prepare" does to the Firefox source, and nothing else:
  1. copies src/jace to engine/browser/jace and writes its moz.build, which
     installs it next to the browser (jacebrowser/, jace.cfg,
     browser/defaults/preferences/jace-prefs.js, distribution/policies.json)
  2. adds "jace" to browser/moz.build's DIRS, and its files to the installer's
     package manifest
  3. makes browser/branding/jace from Firefox's unofficial branding, with the
     Jace Browser name and icons (from branding/logo-1024.png)
  4. writes engine/mozconfig from configs/
"""

