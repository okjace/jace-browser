ROOT = Path(__file__).resolve().parent.parent
ENGINE = ROOT / "engine"
DIST = ROOT / "dist"
CONFIG = json.loads((ROOT / "jace.json").read_text())
VERSION = CONFIG["version"]
FIREFOX = CONFIG["firefox"]
MARK = "# --- Jace Browser ---"


def log(msg):
    print(f"\n==> {msg}", flush=True)


def run(cmd, cwd=None, env=None):
    print("+", " ".join(str(c) for c in cmd), flush=True)
    subprocess.run([str(c) for c in cmd], cwd=cwd, env=env, check=True)


def host_platform():
    return {"Linux": "linux", "Darwin": "macos", "Windows": "windows"}[platform.system()]


# ------------------------------------------------------------------ download

def download(args):
    if (ENGINE / "mach").exists() and (ENGINE / ".jace-firefox-version").read_text().strip() == FIREFOX:
        log(f"Firefox {FIREFOX} source is already in engine/")
        return
    base = f"https://archive.mozilla.org/pub/firefox/releases/{FIREFOX}"
    name = f"firefox-{FIREFOX}.source.tar.xz"
    cache = ROOT / ".cache"
    cache.mkdir(exist_ok=True)
    tarball = cache / name
    log(f"Checking Firefox {FIREFOX}'s published checksum")
    sums = urllib.request.urlopen(f"{base}/SHA512SUMS", timeout=60).read().decode()
    expected = next((l.split()[0] for l in sums.splitlines() if l.endswith(f"source/{name}")), None)
    if not expected:
        sys.exit(f"{name} isn't in SHA512SUMS; is Firefox {FIREFOX} a real release?")
    if not tarball.exists() or sha512(tarball) != expected:
        log(f"Downloading {name}")
        tmp = tarball.with_suffix(".part")
        with urllib.request.urlopen(f"{base}/source/{name}", timeout=120) as r, open(tmp, "wb") as f:
            shutil.copyfileobj(r, f, length=1 << 20)
        tmp.rename(tarball)
    if sha512(tarball) != expected:
        tarball.unlink()
        sys.exit("Checksum mismatch: the download is corrupt. Run again.")
    log("Unpacking")
    if ENGINE.exists():
        shutil.rmtree(ENGINE)
    tmpdir = ROOT / ".engine-unpack"
    shutil.rmtree(tmpdir, ignore_errors=True)
    tmpdir.mkdir()
    run(["tar", "-xf", tarball, "-C", tmpdir])
    (inner,) = list(tmpdir.iterdir())
    inner.rename(ENGINE)
    tmpdir.rmdir()
    (ENGINE / ".jace-firefox-version").write_text(FIREFOX + "\n")


def sha512(path):
    h = hashlib.sha512()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


# ------------------------------------------------------------------ prepare

def files_under(base: Path):
    return sorted(p for p in base.rglob("*") if p.is_file())


def write_jace_mozbuild(jace_dir: Path):
    """moz.build that installs Jace Browser's files next to the browser (dist/bin = GreD)."""
    lines = [
        "# Generated by scripts/build.py prepare. Do not edit.",
        'FINAL_TARGET = "dist/bin"',
        "",
        'FINAL_TARGET_FILES += ["autoconfig/jace.cfg"]',
        'FINAL_TARGET_FILES.browser.defaults.preferences += ["defaults/jace-prefs.js"]',
        'FINAL_TARGET_FILES.distribution += ["policies/policies.json"]',
    ]
    packaged = [
        "@RESPATH@/jace.cfg",
        "@RESPATH@/browser/defaults/preferences/jace-prefs.js",
        "@RESPATH@/distribution/policies.json",
    ]
    groups = {}
    for f in files_under(jace_dir):
        rel = f.relative_to(jace_dir)
        if rel.parts[0] in ("autoconfig", "defaults", "policies") or rel.name == "moz.build":
            continue
        groups.setdefault(rel.parent, []).append(rel)
        packaged.append(f"@RESPATH@/jacebrowser/{rel.as_posix()}")
    for parent, rels in sorted(groups.items()):
        key = ".".join(["jacebrowser", *parent.parts])
        lines.append(f"FINAL_TARGET_FILES.{key} += [")
        lines += [f'    "{r.as_posix()}",' for r in rels]
        lines.append("]")
    (jace_dir / "moz.build").write_text("\n".join(lines) + "\n")
    return packaged


def append_once(path: Path, block: str):
    text = path.read_text()
    if MARK in text:
        text = text[: text.index(MARK)].rstrip() + "\n"
    path.write_text(text + f"\n{MARK}\n{block.strip()}\n")


def make_branding():
    from PIL import Image  # pip install pillow

    src = ENGINE / "browser" / "branding" / "unofficial"
    dst = ENGINE / "browser" / "branding" / "jace"
    shutil.rmtree(dst, ignore_errors=True)
    shutil.copytree(src, dst)
    logo = Image.open(ROOT / "branding" / "logo-1024.png").convert("RGBA")

    def logo_at(w, h):
        side = min(w, h)
        img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
        img.paste(logo.resize((side, side), Image.LANCZOS), ((w - side) // 2, (h - side) // 2))
        return img

    for f in files_under(dst):
        name = f.name.lower()
        if name.endswith(".png") and not name.startswith(("background", "wiz")):
            with Image.open(f) as old:
                size = old.size
            logo_at(*size).save(f)
        elif name.endswith(".ico"):
            logo.save(f, sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
        elif name.endswith(".icns"):
            logo.save(f)
    for svg in ("about-logo.svg",):
        for f in dst.rglob(svg):
            shutil.copy(ROOT / "branding" / "logo.svg", f)
    wordmark = (
        '<svg xmlns="http://www.w3.org/2000/svg" width="210" height="42" viewBox="0 0 210 42">'
        '<text x="0" y="31" font-family="system-ui, sans-serif" font-size="27" font-weight="700" '
        'fill="context-fill">Jace Browser</text></svg>\n'
    )
    for name in ("about-wordmark.svg", "firefox-wordmark.svg"):
        for f in dst.rglob(name):
            f.write_text(wordmark)

    names = {
        "-brand-shorter-name": "Jace",
        "-brand-short-name": "Jace Browser",
        "-brand-shortcut-name": "Jace Browser",
        "-brand-full-name": "Jace Browser",
        "-brand-product-name": "Jace Browser",
        "-vendor-short-name": "Jace",
        "trademarkInfo": "Jace Browser is built on Mozilla Firefox. Firefox is a trademark of the Mozilla Foundation.",
    }
    for ftl in dst.rglob("brand.ftl"):
        text = ftl.read_text()
        for key, value in names.items():
            text = re.sub(rf"^{re.escape(key)}\s*=.*$", f"{key} = {value}", text, flags=re.M)
        ftl.write_text(text)
    props = {
        "brandShorterName": "Jace",
        "brandShortName": "Jace Browser",
        "brandFullName": "Jace Browser",
        "vendorShortName": "Jace",
    }
    for p in dst.rglob("brand.properties"):
        text = p.read_text()
        for key, value in props.items():
            text = re.sub(rf"^{key}\s*=.*$", f"{key}={value}", text, flags=re.M)
        p.write_text(text)
    conf = dst / "configure.sh"
    text = conf.read_text() if conf.exists() else ""
    text = re.sub(r"^MOZ_APP_DISPLAYNAME=.*$", "", text, flags=re.M)
    text = re.sub(r"^MOZ_MACBUNDLE_ID=.*$", "", text, flags=re.M)
    conf.write_text(text.strip() + '\nMOZ_APP_DISPLAYNAME="Jace Browser"\nMOZ_MACBUNDLE_ID=jace\n')

    installer_artwork(dst, logo)

    # The unofficial branding's name ("Mozilla Developer Preview", "Nightly")
    # is also in the Windows installer's branding.nsi (install folder, the
    # installed-apps entry, shortcuts) and a few other text files: Jace there too.
    replacements = [
        ("Mozilla Developer Preview", "Jace Browser"),
        ("MozillaDeveloperPreview", "JaceBrowser"),
        ('!define CompanyName "mozilla.org"', '!define CompanyName "Jace"'),
        ('!define CompanyName "Mozilla Developer Preview"', '!define CompanyName "Jace"'),
    ]
    for f in files_under(dst):
        if f.suffix.lower() not in (".nsi", ".nsh", ".dtd", ".properties", ".ftl", ".sh", ".ini", ".txt", ".json", ".mk", ".build", ".in"):
            continue
        try:
            text = f.read_text()
        except UnicodeDecodeError:
            continue
        new = text
        for old, value in replacements:
            new = new.replace(old, value)
        if new != text:
            f.write_text(new)
    nsi = dst / "branding.nsi"
    if nsi.exists():
        text = nsi.read_text()
        for key, value in [("BrandFullNameInternal", "Jace Browser"), ("BrandShortName", "Jace Browser"), ("BrandFullName", "Jace Browser")]:
            text = re.sub(rf'^(!define {key}\s+)".*"', rf'\1"{value}"', text, flags=re.M)
        nsi.write_text(text)


def installer_artwork(dst: Path, logo):
    """Jace-designed pictures for the Windows installer (NSIS): the tall
    banner on the welcome and finish pages (wizWatermark) and the small one
    at the top of the other pages (wizHeader), instead of Mozilla's."""
    from PIL import Image, ImageDraw, ImageFont

    def font(size, bold=True):
        for path in (
            "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf" if bold else "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
            "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf",
            "/System/Library/Fonts/Supplemental/Arial Bold.ttf",
        ):
            if Path(path).exists():
                return ImageFont.truetype(path, size)
        return ImageFont.load_default()

    def backdrop(w, h):
        # Jace's dark surface with a soft green glow, like the setup pages.
        img = Image.new("RGB", (w, h), (14, 16, 19))
        glow = Image.new("RGB", (w, h), (32, 120, 74))
        mask = Image.new("L", (w, h), 0)
        d = ImageDraw.Draw(mask)
        for i in range(60, 0, -1):
            r = int(max(w, h) * 0.9 * i / 60)
            d.ellipse((-r // 2, -r // 3, r // 2, r // 2), fill=int(150 * (1 - i / 60)))
        return Image.composite(glow, img, mask)

    def paste_logo(img, size, x, y):
        img.paste(logo.resize((size, size), Image.LANCZOS), (x, y), logo.resize((size, size), Image.LANCZOS))

    for bmp in dst.rglob("*.bmp"):
        name = bmp.name.lower()
        with Image.open(bmp) as old:
            w, h = old.size
        if "watermark" in name:
            img = backdrop(w, h)
            paste_logo(img, int(w * 0.5), int(w * 0.25), int(h * 0.18))
            d = ImageDraw.Draw(img)
            d.text((w // 2, int(h * 0.62)), "Jace", font=font(int(w * 0.17)), fill=(230, 232, 235), anchor="mm")
            d.text((w // 2, int(h * 0.71)), "Browser", font=font(int(w * 0.11), bold=False), fill=(61, 220, 132), anchor="mm")
        elif "header" in name:
            img = Image.new("RGB", (w, h), (255, 255, 255))  # header pages are light in NSIS
            paste_logo(img, h - 12, w - h + 4, 6)
        else:
            continue
        if "rtl" in name:
            img = img.transpose(Image.FLIP_LEFT_RIGHT)
        img.save(bmp, format="BMP")


def jace_commit():
    """This repo's commit, which Firefox records as the source changeset (MOZ_SOURCE_CHANGESET)."""
    sha = os.environ.get("GITHUB_SHA")
    if not sha:
        res = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True)
        sha = res.stdout.strip() if res.returncode == 0 else ""
    return sha or "unknown"


def patch_vendor():
    """Makes the vendor Jace instead of Mozilla, wherever this Firefox sets it."""
    done = []
    pattern = re.compile(r'(imply_option\(\s*"MOZ_APP_VENDOR"\s*,\s*)"Mozilla"')
    for conf in [ENGINE / "browser" / "moz.configure", ENGINE / "build" / "moz.configure" / "init.configure"]:
        if conf.exists():
            text = conf.read_text()
            new = pattern.sub(r'\1"Jace"', text)
            if new != text:
                conf.write_text(new)
                done.append(str(conf.relative_to(ENGINE)))
    return ", ".join(done)


def write_mozconfig(target):
    text = (ROOT / "configs" / "mozconfig.common").read_text()
    text += "\n" + (ROOT / "configs" / f"mozconfig.{target}").read_text()
    text = text.replace("@JACE_COMMIT@", jace_commit())
    winsysroot = Path.home() / "win-cross" / "vs"
    if winsysroot.exists():
        text = text.replace("@WINSYSROOT@", str(winsysroot))
    else:
        # No packed SDK: --enable-bootstrap downloads Mozilla's Windows SDK toolchain instead.
        text = "\n".join(line for line in text.splitlines() if "@WINSYSROOT@" not in line) + "\n"
    mac_arch = os.environ.get("JACE_MAC_ARCH")
    if target == "macos" and mac_arch:
        # CI builds both Mac versions on Apple Silicon machines.
        triple = {"x86_64": "x86_64-apple-darwin", "arm64": "aarch64-apple-darwin"}[mac_arch]
        text += f"\nac_add_options --target={triple}\n"
    if target == "macos" and "@MACOS_SDK@" in text:
        sdk = subprocess.run(["xcrun", "--show-sdk-path"], capture_output=True, text=True).stdout.strip()
        text = text.replace("@MACOS_SDK@", sdk)
    if shutil.which("sccache"):
        # Compiler cache (C, C++ and Rust): rebuilds only recompile what changed.
        # In CI it's stored in GitHub's cache (SCCACHE_GHA_ENABLED); locally in ~/.cache.
        text += "\n# Added by scripts/build.py because sccache is installed\nac_add_options --with-ccache=sccache\n"
    (ENGINE / "mozconfig").write_text(text)


def prepare(args):
    if not (ENGINE / "mach").exists():
        sys.exit("No Firefox source in engine/. Run: python3 scripts/build.py download")
    log("Adding Jace Browser to the Firefox source")
    jace_dir = ENGINE / "browser" / "jace"
    shutil.rmtree(jace_dir, ignore_errors=True)
    shutil.copytree(ROOT / "src" / "jace", jace_dir, ignore=shutil.ignore_patterns("README.md"))
    with open(jace_dir / "defaults" / "jace-prefs.js", "a") as f:
        f.write(f'\n// Set by scripts/build.py\npref("jace.version", "{VERSION}");\n')

    helper = Path(args.usb_helper) if args.usb_helper else default_usb_helper(args.platform)
    if helper and helper.exists():
        (jace_dir / "bin").mkdir(exist_ok=True)
        dest = jace_dir / "bin" / ("jace-usb-helper.exe" if args.platform == "windows" else "jace-usb-helper")
        shutil.copy(helper, dest)
        dest.chmod(0o755)
    else:
        print(f"warning: no USB helper ({helper}); WebUSB won't reach devices in this build", flush=True)

    packaged = write_jace_mozbuild(jace_dir)
    append_once(ENGINE / "browser" / "moz.build", 'DIRS += ["jace"]')
    append_once(
        ENGINE / "browser" / "installer" / "package-manifest.in",
        "[jace]\n" + "\n".join(packaged),
    )
    log("Branding")
    make_branding()
    log("Vendor name (Windows file details, application.ini)")
    patched = patch_vendor()
    print(f"  {patched or 'not found in this Firefox version; vendor stays Mozilla'}", flush=True)
    log("Rewriting leftover Firefox / Mozilla text (debrand)")
    import debrand  # scripts/debrand.py

    changed = 0
    for locales in ("browser/locales/en-US", "toolkit/locales/en-US", "devtools/client/locales/en-US", "dom/locales/en-US"):
        if (ENGINE / locales).exists():
            changed += debrand.rewrite_tree(ENGINE / locales)
    print(f"  {changed} files", flush=True)
    write_mozconfig(args.platform)
    log("Ready: engine/ has Jace Browser in it")


def default_usb_helper(target):
    triple = {"windows": "x86_64-pc-windows-msvc"}.get(target)
    base = ROOT / "usb-helper" / "target"
    exe = "jace-usb-helper.exe" if target == "windows" else "jace-usb-helper"
    for p in ([base / triple / "release" / exe] if triple else []) + [base / "release" / exe]:
        if p.exists():
            return p
    if target == host_platform():
        log("Building the USB helper")
        run(["cargo", "build", "--release"], cwd=ROOT / "usb-helper")
        return base / "release" / exe
    return None


# ------------------------------------------------------------------ build

def vs_sdk(args):
    """Windows cross-build: Visual Studio's headers/libs from Microsoft, via Firefox's own script."""
    out = Path.home() / "win-cross"
    if (out / "vs").exists():
        log("Visual Studio SDK already unpacked")
        return
    # Newer Firefox moved (or dropped) pack_vs.py; then --enable-bootstrap
    # downloads Mozilla's own packaged Windows SDK during the build instead.
    scripts = sorted(p for p in ENGINE.rglob("pack_vs.py") if "obj-" not in str(p))
    yamls = sorted((ENGINE / "build" / "vs").glob("vs20*.yaml"))
    if not scripts or not yamls:
        log("No pack_vs.py in this Firefox: the build's bootstrap will download the Windows SDK itself")
        return
    out.mkdir(exist_ok=True)
    archive = out / "vs.tar.zst"
    yaml = yamls[-1]
    script = scripts[0].relative_to(ENGINE)
    log(f"Packing the Windows SDK and MSVC ({yaml.name} with {script}); this downloads from Microsoft")
    run(["./mach", "python", "--virtualenv", "build", script, yaml.relative_to(ENGINE), "-o", archive], cwd=ENGINE)
    run(["tar", "--zstd", "-xf", archive, "-C", out])
    archive.unlink()


def build(args):
    # Written again here, so a Windows SDK unpacked after "prepare" is picked up.
    write_mozconfig(args.platform)
    env = {**os.environ, "MOZBUILD_STATE_PATH": str(Path.home() / ".mozbuild"), "MACH_BUILD_PYTHON_NATIVE_PACKAGE_SOURCE": "pip"}
    if args.bootstrap:
        log("Installing build tools (mach bootstrap)")
        run(["./mach", "--no-interactive", "bootstrap", "--application-choice", "browser"], cwd=ENGINE, env=env)
    log("Building (this takes a while)")
    try:
        run(["./mach", "build"], cwd=ENGINE, env=env)
    finally:
        if shutil.which("sccache"):
            log("Compiler cache")
            subprocess.run(["sccache", "--show-stats"], check=False)


# ------------------------------------------------------------------ package

def package(args):
    DIST.mkdir(exist_ok=True)
    obj = ENGINE / "obj-jace"
    stem = f"JaceBrowser-{VERSION}"
    log("Packaging")
    run(["./mach", "package"], cwd=ENGINE)
    if args.platform == "linux":
        (tarball,) = [p for p in (obj / "dist").glob("jace-*.tar.*")]
        out = DIST / f"{stem}-linux-x86_64.tar.xz"
        repack_linux(tarball, out)
        make_appimage(out, DIST / f"{stem}-x86_64.AppImage")
    elif args.platform == "windows":
        # Newer Firefox makes the setup .exe during `mach package`
        # (dist/jace-*.installer.exe); older ones need the "installer" target
        # (dist/install/sea/*.exe).
        setups = list((obj / "dist").glob("jace-*.installer.exe")) or list((obj / "dist" / "install" / "sea").glob("*.exe"))
        if not setups:
            run(["./mach", "build", "installer"], cwd=ENGINE)
            setups = list((obj / "dist" / "install" / "sea").glob("*.exe")) or list((obj / "dist").glob("jace-*.installer.exe"))
        (setup,) = setups
        shutil.copy(setup, DIST / f"{stem}-windows-x64-setup.exe")
        # The browser zip (Firefox also leaves e.g. *.xpt_artifacts.zip there).
        (zipped,) = [p for p in (obj / "dist").glob("jace-*.zip") if p.name.count(".") <= 4 and "artifacts" not in p.name and "symbols" not in p.name]
        shutil.copy(zipped, DIST / f"{stem}-windows-x64-portable.zip")
    elif args.platform == "macos":
        arch = os.environ.get("JACE_MAC_ARCH") or ("arm64" if platform.machine() == "arm64" else "x86_64")
        (dmg,) = list((obj / "dist").glob("jace-*.dmg"))
        make_dmg(dmg, DIST / f"{stem}-macos-{arch}.dmg")
    for f in sorted(DIST.iterdir()):
        print(f"  {f.name}  ({f.stat().st_size // (1 << 20)} MB)")


AUTOCONFIG_JS = """// Jace Browser: load jace.cfg at startup (see jace.cfg). Also in
// jace-prefs.js; here too because this is where Firefox documents it.
pref("general.config.filename", "jace.cfg");
pref("general.config.obscure_value", 0);
pref("general.config.sandbox_enabled", false);
"""


def add_autoconfig(install: Path):
    """defaults/pref/autoconfig.js on disk next to the browser."""
    pref_dir = install / "defaults" / "pref"
    pref_dir.mkdir(parents=True, exist_ok=True)
    (pref_dir / "autoconfig.js").write_text(AUTOCONFIG_JS)


def repack_linux(tarball: Path, out: Path):
    """Make sure the USB helper is executable, and use .tar.xz."""
    work = ROOT / ".pkg"
    shutil.rmtree(work, ignore_errors=True)
    work.mkdir()
    run(["tar", "-xf", tarball, "-C", work])
    helper = work / "jace" / "jacebrowser" / "bin" / "jace-usb-helper"
    if helper.exists():
        helper.chmod(0o755)
    add_autoconfig(work / "jace")
    run(["tar", "-cJf", out, "-C", work, "jace"])


def make_appimage(tarball: Path, out: Path):
    appdir = ROOT / ".pkg" / "Jace_Browser.AppDir"
    shutil.rmtree(appdir, ignore_errors=True)
    (appdir / "usr" / "lib").mkdir(parents=True)
    run(["tar", "-xf", tarball, "-C", appdir / "usr" / "lib"])
    shutil.copy(ROOT / "packaging" / "appimage" / "AppRun", appdir / "AppRun")
    (appdir / "AppRun").chmod(0o755)
    shutil.copy(ROOT / "packaging" / "appimage" / "jace-browser.desktop", appdir / "jace-browser.desktop")
    from PIL import Image
    Image.open(ROOT / "branding" / "logo-1024.png").resize((256, 256), Image.LANCZOS).save(appdir / "jace-browser.png")
    (appdir / ".DirIcon").symlink_to("jace-browser.png")
    tool = ROOT / ".cache" / "appimagetool"
    if not tool.exists():
        url = "https://github.com/AppImage/appimagetool/releases/download/continuous/appimagetool-x86_64.AppImage"
        urllib.request.urlretrieve(url, tool)
        tool.chmod(0o755)
    run([tool, "--no-appstream", appdir, out], env={**os.environ, "ARCH": "x86_64", "APPIMAGE_EXTRACT_AND_RUN": "1"})


def make_dmg(source_dmg: Path, out: Path):
    """Re-make the DMG with an ad-hoc signed app and an Applications shortcut to drag onto."""
    mnt = ROOT / ".pkg" / "mnt"
    stage = ROOT / ".pkg" / "dmg"
    shutil.rmtree(ROOT / ".pkg", ignore_errors=True)
    mnt.mkdir(parents=True)
    stage.mkdir()
    run(["hdiutil", "attach", "-nobrowse", "-readonly", "-mountpoint", mnt, source_dmg])
    try:
        (app,) = list(mnt.glob("*.app"))
        # Without resource forks / Finder info: codesign refuses an app that has them.
        run(["ditto", "--norsrc", "--noextattr", "--noqtn", app, stage / "Jace Browser.app"])
    finally:
        run(["hdiutil", "detach", mnt])
    helper = stage / "Jace Browser.app" / "Contents" / "Resources" / "jacebrowser" / "bin" / "jace-usb-helper"
    if helper.exists():
        helper.chmod(0o755)
    # Not notarized (no paid Apple certificate), but a valid ad-hoc signature is
    # required on Apple Silicon and avoids the "damaged" message.
    run(["xattr", "-cr", stage / "Jace Browser.app"])
    run(["codesign", "--force", "--deep", "--sign", "-", stage / "Jace Browser.app"])
    (stage / "Applications").symlink_to("/Applications")
    run(["hdiutil", "create", "-volname", "Jace Browser", "-srcfolder", stage, "-ov", "-format", "UDZO", out])


# ------------------------------------------------------------------ main

def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("step", choices=["download", "prepare", "vs-sdk", "build", "package", "all", "version"])
    p.add_argument("--platform", choices=["linux", "windows", "macos"], default=host_platform())
    p.add_argument("--usb-helper", help="path to a prebuilt jace-usb-helper for --platform")
    p.add_argument("--no-bootstrap", dest="bootstrap", action="store_false", help="skip mach bootstrap")
    args = p.parse_args()
    if args.step == "version":
        print(VERSION)
        return
    steps = {
        "download": [download],
        "prepare": [prepare],
        "vs-sdk": [vs_sdk],
        "build": [build],
        "package": [package],
        "all": [download, prepare] + ([vs_sdk] if args.platform == "windows" else []) + [build, package],
    }[args.step]
    for step in steps:
        step(args)


if __name__ == "__main__":
    main()
